/**
 * Bundled, fully-offline emoji catalog.
 *
 * The catalog is declared as a compile-time constant list so there is no parsing,
 * I/O, or allocation churn at runtime — it is materialized once on first access and
 * shared immutably. No internet, no remote fetch (privacy + offline-first).
 *
 * Each entry carries a canonical [Emoji.name] (used for the accessibility label and as
 * the primary search field) plus [Emoji.keywords] (synonyms for search recall).
 *
 * This is a curated, representative subset covering every category. It is intentionally
 * data-table driven (per CLAUDE.md) so it can be expanded without code changes.
 */
internal object EmojiCatalog {

    /**
     * The full ordered catalog. Order within a category is the display order in the
     * grid. Built eagerly into a `List` once and reused; callers must not mutate it.
     */
    val all: List<Emoji> = buildList {
        addSmileys()
        addPeople()
        addAnimals()
        addFood()
        addActivity()
        addTravel()
        addObjects()
        addSymbols()
        addFlags()
    }

    /** Catalog grouped by category for O(1) category lookups. RECENT is excluded. */
    val byCategory: Map<EmojiCategory, List<Emoji>> =
        all.groupBy { it.category }

    private fun MutableList<Emoji>.emoji(
        glyph: String,
        name: String,
        category: EmojiCategory,
        vararg keywords: String,
    ) = add(Emoji(glyph = glyph, name = name, keywords = keywords.asList(), category = category))

